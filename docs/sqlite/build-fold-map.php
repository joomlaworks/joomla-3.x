 * Writes libraries/joomla/database/mysqlonsqlite/foldmap.php: the letters JDatabaseMysqlonsqliteFunctions::fold() changes, for
 * servers without PHP's intl extension. For every character of the scripts below, its case-folded form maps to that form without
 * accents (NFKD, combining marks removed), as fold() does with intl. Run with PHP and intl: php docs/sqlite/build-fold-map.php
 */

if (!class_exists('Normalizer')) {
    fwrite(STDERR, "PHP's intl extension is needed.\n");
    exit(1);
}

$ranges = array(
    array(0x00C0, 0x024F), // Latin-1 Supplement, Latin Extended-A and -B
    array(0x0370, 0x03FF), // Greek and Coptic
    array(0x0400, 0x04FF), // Cyrillic
    array(0x1E00, 0x1EFF), // Latin Extended Additional (e.g. Vietnamese)
    array(0x1F00, 0x1FFF), // Greek Extended (polytonic)
    array(0xFB00, 0xFB06), // Latin ligatures (ﬁ)
    array(0xFF01, 0xFF5E), // Full-width ASCII
);

$fold = function ($string) {
    $string = preg_replace('/\p{Mn}+/u', '', Normalizer::normalize($string, Normalizer::FORM_KD));

    return mb_convert_case($string, MB_CASE_FOLD, 'UTF-8');
};

$map = array();

foreach ($ranges as $range) {
    for ($code = $range[0]; $code <= $range[1]; $code++) {
        $char = mb_chr($code, 'UTF-8');

        if ($char === false || !preg_match('/^\p{L}$/u', $char)) {
            continue;
        }

        $key   = mb_convert_case($char, MB_CASE_FOLD, 'UTF-8');
        $value = $fold($char);

        if ($key !== $value && mb_strlen($key, 'UTF-8') === 1 && !isset($map[$key])) {
            $map[$key] = $value;
        }
    }
}

ksort($map, SORT_STRING);

$lines = array();

foreach (array_chunk($map, 8, true) as $chunk) {
    $pairs = array();

    foreach ($chunk as $key => $value) {
        $pairs[] = var_export((string) $key, true) . ' => ' . var_export($value, true);
    }

    $lines[] = "\t" . implode(', ', $pairs) . ',';
}

$file = dirname(__DIR__, 2) . '/libraries/joomla/database/mysqlonsqlite/foldmap.php';

file_put_contents($file, "<?php\n/**\n * @package     Joomla.Platform\n * @subpackage  Database\n *\n"
    . " * @copyright   (C) 2026 JoomlaWorks Ltd. and this project's contributors\n"
    . " * @license     GNU General Public License version 2 or later; see LICENSE.md\n *\n"
    . " * Case-folded letters and their forms without accents, for JDatabaseMysqlonsqliteFunctions::fold() without PHP's intl\n"
    . " * extension. Generated by docs/sqlite/build-fold-map.php: don't edit by hand.\n */\n\n"
    . "defined('JPATH_PLATFORM') or die;\n\nreturn array(\n" . implode("\n", $lines) . "\n);\n");

echo count($map), " letters written to $file\n";
